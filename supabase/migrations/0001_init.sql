-- =============================================================================
-- Migracion inicial: esquema de facturacion sobre Supabase
-- Ejecutar en: Supabase Dashboard > SQL Editor (o `supabase db push`)
-- Cubre: tablas, trigger de perfiles, RLS, GRANTs explicitos y realtime.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1) Perfiles de usuario (reemplaza el arbol "users" de Firebase)
-- -----------------------------------------------------------------------------
create table if not exists public.profiles (
    id          uuid primary key references auth.users (id) on delete cascade,
    email       text not null,
    role        text not null default 'user' check (role in ('user', 'admin')),
    description text not null default '',
    created_at  timestamptz not null default now()
);

create unique index if not exists profiles_email_key on public.profiles (lower(email));

-- -----------------------------------------------------------------------------
-- 2) Helper: saber si el usuario autenticado es admin (evita recursion en RLS)
-- -----------------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.profiles p
        where p.id = auth.uid() and p.role = 'admin'
    );
$$;

-- -----------------------------------------------------------------------------
-- 3) Facturas (reemplaza el arbol "invoices" de Firebase)
-- -----------------------------------------------------------------------------
create table if not exists public.invoices (
    id               bigint primary key,
    number           text,
    client           text,
    address          text,
    date             text,
    amount           numeric not null default 0,
    status           text not null default 'pending',
    abono            numeric not null default 0,
    saldo_actual     numeric not null default 0,
    dispatch_detail  text,
    due_date         text,
    paid_date        text,
    items            jsonb not null default '[]'::jsonb,
    change_log       jsonb not null default '[]'::jsonb,
    owner_id         uuid references auth.users (id) on delete set null,
    created_by_email text,
    created_at       text,
    updated_by_email text,
    updated_at       text
);

create index if not exists invoices_owner_id_idx on public.invoices (owner_id);
create index if not exists invoices_status_idx on public.invoices (status);

-- -----------------------------------------------------------------------------
-- 4) Auditoria de acciones admin (reemplaza el arbol "adminAudit")
-- -----------------------------------------------------------------------------
create table if not exists public.admin_audit (
    id          bigint generated by default as identity primary key,
    time        timestamptz not null default now(),
    admin_email text,
    action      text,
    target      text
);

-- -----------------------------------------------------------------------------
-- 5) Trigger: crear el perfil automaticamente al registrar un usuario auth
-- -----------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, email, role)
    values (
        new.id,
        new.email,
        coalesce(new.raw_user_meta_data ->> 'role', 'user')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- -----------------------------------------------------------------------------
-- 6) Row Level Security
-- -----------------------------------------------------------------------------
alter table public.profiles    enable row level security;
alter table public.invoices    enable row level security;
alter table public.admin_audit enable row level security;

-- Perfiles: cada quien ve el suyo; el admin ve todos y gestiona.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles
    for select to authenticated
    using (id = auth.uid() or public.is_admin());

drop policy if exists profiles_update on public.profiles;
create policy profiles_update on public.profiles
    for update to authenticated
    using (public.is_admin())
    with check (public.is_admin());

-- Facturas: dueño o admin.
drop policy if exists invoices_select on public.invoices;
create policy invoices_select on public.invoices
    for select to authenticated
    using (owner_id = auth.uid() or public.is_admin());

drop policy if exists invoices_insert on public.invoices;
create policy invoices_insert on public.invoices
    for insert to authenticated
    with check (owner_id = auth.uid() or public.is_admin());

drop policy if exists invoices_update on public.invoices;
create policy invoices_update on public.invoices
    for update to authenticated
    using (owner_id = auth.uid() or public.is_admin())
    with check (owner_id = auth.uid() or public.is_admin());

drop policy if exists invoices_delete on public.invoices;
create policy invoices_delete on public.invoices
    for delete to authenticated
    using (owner_id = auth.uid() or public.is_admin());

-- Auditoria: cualquier usuario autenticado puede registrar acciones; solo admin lee.
drop policy if exists admin_audit_select on public.admin_audit;
create policy admin_audit_select on public.admin_audit
    for select to authenticated
    using (public.is_admin());

drop policy if exists admin_audit_insert on public.admin_audit;
create policy admin_audit_insert on public.admin_audit
    for insert to authenticated
    with check (true);

-- -----------------------------------------------------------------------------
-- 7) GRANTs explicitos (necesarios porque el proyecto NO auto-expone tablas)
-- -----------------------------------------------------------------------------
grant usage on schema public to anon, authenticated, service_role;

grant select, update on public.profiles to authenticated;
grant select, insert, update, delete on public.invoices to authenticated;
grant select, insert on public.admin_audit to authenticated;
grant usage on sequence public.admin_audit_id_seq to authenticated;

grant all privileges on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;

-- -----------------------------------------------------------------------------
-- 8) Realtime (reemplaza los listeners onValue de Firebase)
-- -----------------------------------------------------------------------------
do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'invoices'
    ) then
        alter publication supabase_realtime add table public.invoices;
    end if;

    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'profiles'
    ) then
        alter publication supabase_realtime add table public.profiles;
    end if;
end $$;
